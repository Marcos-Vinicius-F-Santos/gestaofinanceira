function compactText(value) {
  return String(value || '').trim().replace(/\s+/g, ' ');
}

export function normalizeImportKey(value) {
  return compactText(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

export function normalizeImportTipo(value) {
  const normalized = normalizeImportKey(value);

  if (normalized === 'receita') return 'receita';
  if (normalized === 'despesa') return 'despesa';
  return '';
}

function parseSeparatedLine(line) {
  if (line.includes('\t')) return line.split('\t').map(compactText);
  if (!line.includes(',') && !line.includes(';')) return line.split(/\s{2,}/).map(compactText);

  const delimiter = line.includes(';') && !line.includes(',') ? ';' : ',';
  const values = [];
  let current = '';
  let inQuotes = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const nextChar = line[index + 1];

    if (char === '"' && inQuotes && nextChar === '"') {
      current += '"';
      index += 1;
    } else if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === delimiter && !inQuotes) {
      values.push(compactText(current));
      current = '';
    } else {
      current += char;
    }
  }

  values.push(compactText(current));
  return values;
}

function isHeader(columns) {
  return (
    normalizeImportKey(columns[0]) === 'conta'
    && normalizeImportKey(columns[1]) === 'subconta'
    && normalizeImportKey(columns[2]) === 'tipo'
  );
}

export function rowsToPlanoContasText(rows, delimiter = '\t') {
  const lines = ['Conta', 'Subconta', 'Tipo'].join(delimiter);
  const dataLines = rows.map((row) => [row.conta, row.subconta, row.tipo].join(delimiter));
  return [lines, ...dataLines].join('\n');
}

export function getDefaultPlanoContasText() {
  return rowsToPlanoContasText(DEFAULT_PLANO_CONTAS_ROWS);
}

